-- Päivitys
with upd as (
  update players p
     set mpg_base = s.mpg, active = s.active
    from sheet_mins s
   where p.team = s.team
     and pg_temp.norm_name(p.name) = pg_temp.norm_name(s.name)
     and not exists (select 1 from transactions t where t.player_name = p.name and t.team = p.team)
  returning p.id
)
insert into sheet_updated select id from upd;

-- Tulos: ensimmäinen rivi = päivitettyjen määrä, sen jälkeen taulukon rivit,
-- joita ei löytynyt samasta joukkueesta (jo siirretty, eri nimi kannassa tms.)
select 'PÄIVITETTY' as tila, (select count(*) from sheet_updated)::text as joukkue, '' as pelaaja, null::numeric as minuutit
union all
(select 'ei löytynyt', s.team, s.name, s.mpg
   from sheet_mins s
  where not exists (
    select 1 from players p
     where p.team = s.team and pg_temp.norm_name(p.name) = pg_temp.norm_name(s.name))
  order by s.team, s.name);
